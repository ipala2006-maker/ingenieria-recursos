import crypto from 'node:crypto';
import production from './push-worker.mjs';
import { preparePush } from './push.mjs';
import dispatcher from '../api/_lib/push-dispatch.js';

export default {
  async fetch(request, env) {
    if (new URL(request.url).pathname !== '/__cpu_probe') return production.fetch(request, env);
    const expected = Buffer.from(env.CPU_PROBE_TOKEN || ''), provided = Buffer.from((request.headers.get('authorization') || '').replace(/^Bearer /, ''));
    if (request.method !== 'POST' || expected.length < 32 || expected.length !== provided.length || !crypto.timingSafeEqual(expected, provided)) {
      return Response.json({ message: 'Unauthorized' }, { status: 401 });
    }
    const text = await request.text();
    if (text.length > 4096) return Response.json({ message: 'Fixture too large' }, { status: 413 });
    // Fixture keys are generated by the benchmark client, like existing keys in
    // real delivery. Key generation is not part of dispatch CPU in production.
    const { subscription, vapid } = JSON.parse(text);
    const jobs = Array.from({ length: 2 }, (_, index) => ({ id: index + 1, subscription, title: 'Repasar para el parcial', tag: 'fixture-only', owner: '00000000-0000-4000-8000-000000000001' }));
    // Four fetches through the real static asset binding. Never contact a push
    // provider, claim a database job, or use a real user's subscription.
    let fixtureStatus = null;
    const exchange = async () => {
      const response = await env.ASSETS.fetch(new Request(new URL('/widgets/calendar-template.json', request.url)));
      fixtureStatus = response.status;
      if (!response.ok) throw new Error('Fixture unavailable');
      return response.json();
    };
    try {
      const result = await dispatcher.dispatchPush({
        profile: 'cloudflare-free-small',
        rpc: async name => { await exchange(); return name === 'claim_mobile_push_batch' ? jobs : null; },
        send: async job => {
          await preparePush(job.subscription, { title: job.title, body: 'Es hora de tu tarea.', tag: job.tag, owner: job.owner }, vapid);
          await exchange();
        }
      });
      return Response.json({ ...result, synthetic: true, productionDeliveryVerified: false }, { headers: { 'Cache-Control': 'no-store' } });
    } catch (error) {
      return Response.json({ message: 'Probe failed', fixtureStatus, errorType: error.name, errorCode: error.code,
        diagnostic: String(error.message).slice(0, 180) }, { status: 503 });
    }
  }
};
